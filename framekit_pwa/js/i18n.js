export function translateSpotTag(tag) {
  return currentLang === "en" ? (SPOT_TAG_EN[tag] || tag) : tag;
}

export function translateMoodCat(cat) {
  return currentLang === "en" ? (MOOD_CAT_EN[cat] || cat) : cat;
}

export function translateCheckItem(item) {
  if (currentLang !== "en") return { cat: item.cat || "Своє", text: item.text };
  if (DEFAULT_CHECK_EN[item.id]) return DEFAULT_CHECK_EN[item.id];
  const catMap = {
    "Живлення й пам'ять": "Power & Memory",
    "Камера й оптика": "Camera & Optics",
    "Аксесуари": "Accessories",
    "Своє": "Custom",
  };
  return { cat: catMap[item.cat] || item.cat || "Custom", text: item.text };
}

export function translateLightingScheme(sc) {
  if (currentLang !== "en") {
    return { ...sc, short: sc.name.split(" (")[0] };
  }
  const en = LIGHTING_EN[sc.id];
  return en ? { ...sc, ...en } : { ...sc, short: sc.name.split(" (")[0] };
}

export function translateNdFilter(f) {
  if (currentLang !== "en") return f.label;
  if (f.stops === 0) return "No filter (0 stops)";
  if (f.stops === 1.5) return "CPL Polarizer (~1.5 stops)";
  const prefix = f.label.split(" / ")[0];
  return `${prefix} / ${f.stops} ${f.stops === 1 ? "stop" : "stops"})`;
}

export function formatStopsBadge(stops) {
  if (currentLang === "en") return `+${stops} ${stops === 1 ? "stop" : "stops"}`;
  const suffix = stops === 1 ? "" : stops < 5 ? "и" : "ів";
  return `+${stops} стоп${suffix}`;
}

