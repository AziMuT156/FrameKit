export const SUPPORTED_LANGS = [
  { code: "uk", label: "Українська (UA)", short: "UA" },
  { code: "en", label: "English (EN)", short: "EN" },
];

let currentLang = "uk";

export function getLang() {
  return currentLang;
}

export function setLang(code) {
  currentLang = DICT[code] ? code : "uk";
  document.documentElement.lang = currentLang;
  return currentLang;
}

export function t(key, vars = null) {
  const table = DICT[currentLang] || DICT.uk;
  let str = table[key] ?? DICT.uk[key] ?? key;
  if (vars) {
    for (const [k, v] of Object.entries(vars)) {
      str = str.replaceAll(`{${k}}`, String(v));
    }
  }
  return str;
}

export function applyDomI18n(root = document) {
  root.querySelectorAll("[data-i18n]").forEach((el) => {
    el.textContent = t(el.dataset.i18n);
  });
  root.querySelectorAll("[data-i18n-html]").forEach((el) => {
    el.innerHTML = t(el.dataset.i18nHtml);
  });
  root.querySelectorAll("[data-i18n-placeholder]").forEach((el) => {
    el.setAttribute("placeholder", t(el.dataset.i18nPlaceholder));
  });
  root.querySelectorAll("[data-i18n-title]").forEach((el) => {
    el.setAttribute("title", t(el.dataset.i18nTitle));
  });
  document.title = t("page_title");
}

